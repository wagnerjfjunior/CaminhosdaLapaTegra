// Validate the standalone real-estate business entity and its visible source facts.
import {readFileSync} from "node:fs";
import assert from "node:assert/strict";
const html=readFileSync("index.html","utf8");
const scripts=[...html.matchAll(/<script\b([^>]*)type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/gi)];
assert.equal(scripts.length,2,"expect main graph and independent business JSON-LD");
const main=JSON.parse(scripts[0][2]), agent=JSON.parse(scripts[1][2]);
const origin="https://www.caminhosdalapategra.com.br/";
assert.equal(agent["@type"],"RealEstateAgent");
assert.equal(agent["@id"],origin+"#sabrina-real-estate-agent");
assert.equal(agent.url,origin);
assert.equal(agent.sameAs,"https://corretor.tegravendas.com.br/sabrina/sp");
assert.equal(agent.telephone,"+5511960779328");
assert.equal(agent.identifier?.value,"209.905-F");
assert.equal(agent.address?.streetAddress,"Rua Fortunato Ferraz, 625");
assert.equal(agent.address?.postalCode,"05093-000");
assert.equal(agent.address?.addressCountry,"BR");
assert.equal(agent.geo?.latitude,-23.517165527430233);
assert.equal(agent.geo?.longitude,-46.71861778788628);
assert.ok(agent.image?.startsWith("https://"));
assert.ok(agent.logo?.startsWith("https://"));
assert.ok(html.includes("Rua Fortunato Ferraz, 625")&&html.includes("CEP 05093-000"),"business location must be disclosed in rendered page");
assert.ok(html.includes("CRECI-SP 209.905-F")&&html.includes("(11) 96077-9328"),"identity and contact must be visible");
const nodes=main["@graph"];
const org=nodes.find(x=>x["@type"]==="Organization");
assert.equal(org?.["@id"],origin+"#tegra-vendas");
assert.ok(org?.logo);
const service=nodes.find(x=>x["@type"]==="Service");
assert.deepEqual(service?.provider,{"@id":agent["@id"]});
assert.equal(nodes.filter(x=>x["@type"]==="FAQPage").length,1);
assert.equal(nodes.filter(x=>x["@type"]==="Product"||x["@type"]==="Offer"||x["@type"]==="VideoObject").length,0);
console.log("Independent RealEstateAgent rich-result candidate and Organization facts: PASS");
